<?php

namespace Tests\Unit;

use App\Services\Vtt\Cue;
use App\Services\Vtt\VttParseException;
use App\Services\Vtt\VttParser;
use PHPUnit\Framework\TestCase;

class VttParserTest extends TestCase
{
    private VttParser $parser;

    protected function setUp(): void
    {
        $this->parser = new VttParser;
    }

    public function test_parses_zoom_speaker_prefixes_timings_and_identifiers(): void
    {
        $cues = $this->parser->parse(<<<'VTT'
WEBVTT

1
00:00:02.140 --> 00:00:07.920
Dana Reyes: Okay, let's get started.

2
01:02:03.500 --> 01:02:05.000
Jordan's iPhone: Worst case is O of n.
VTT);

        $this->assertCount(2, $cues);
        $this->assertSame('Dana Reyes', $cues[0]->speaker);
        $this->assertSame("Okay, let's get started.", $cues[0]->text);
        $this->assertSame('1', $cues[0]->identifier);
        $this->assertSame(2140, $cues[0]->startMs);
        $this->assertSame(7920, $cues[0]->endMs);
        $this->assertSame("Jordan's iPhone", $cues[1]->speaker);
        $this->assertSame(3723500, $cues[1]->startMs);
    }

    public function test_handles_crlf_bom_hourless_timestamps_cue_settings_and_no_identifiers(): void
    {
        $vtt = "\xEF\xBB\xBFWEBVTT - Zoom export\r\n\r\n00:05.000 --> 00:07.250 align:start position:10%\r\nMarcus Lee: Is it due Friday?\r\n";

        $cues = $this->parser->parse($vtt);

        $this->assertCount(1, $cues);
        $this->assertNull($cues[0]->identifier);
        $this->assertSame(5000, $cues[0]->startMs);
        $this->assertSame(7250, $cues[0]->endMs);
        $this->assertSame('Marcus Lee', $cues[0]->speaker);
        $this->assertSame('Is it due Friday?', $cues[0]->text);
    }

    public function test_multi_line_cue_text_is_joined_under_one_speaker(): void
    {
        $cues = $this->parser->parse("WEBVTT\n\n00:00:01.000 --> 00:00:04.000\nPriya Patel: You keep a linked list\nat that bucket.\n");

        $this->assertSame('Priya Patel', $cues[0]->speaker);
        $this->assertSame('You keep a linked list at that bucket.', $cues[0]->text);
    }

    public function test_supports_webvtt_voice_tags(): void
    {
        $cues = $this->parser->parse("WEBVTT\n\n00:00:01.000 --> 00:00:02.000\n<v Grace Kim>Sorry I'm late &amp; lost.</v>\n");

        $this->assertSame('Grace Kim', $cues[0]->speaker);
        $this->assertSame("Sorry I'm late & lost.", $cues[0]->text);
    }

    public function test_cue_without_speaker_is_attributed_to_unknown(): void
    {
        $cues = $this->parser->parse("WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nokay can everyone hear me\n");

        $this->assertSame(VttParser::UNKNOWN_SPEAKER, $cues[0]->speaker);
        $this->assertSame('okay can everyone hear me', $cues[0]->text);
    }

    public function test_colon_inside_a_sentence_is_not_mistaken_for_a_speaker(): void
    {
        $cues = $this->parser->parse(<<<'VTT'
WEBVTT

00:00:01.000 --> 00:00:02.000
Here is the thing I keep forgetting about this whole idea: it works.

00:00:03.000 --> 00:00:04.000
See https://example.com: the docs.
VTT);

        $this->assertSame(VttParser::UNKNOWN_SPEAKER, $cues[0]->speaker);
        $this->assertSame(VttParser::UNKNOWN_SPEAKER, $cues[1]->speaker);
    }

    public function test_skips_note_and_style_blocks_and_empty_cues(): void
    {
        $cues = $this->parser->parse(<<<'VTT'
WEBVTT

NOTE This transcript was generated by Zoom

STYLE
::cue { color: yellow }

00:00:01.000 --> 00:00:02.000

00:00:03.000 --> 00:00:04.000
Dana Reyes: Hello.
VTT);

        $this->assertCount(1, $cues);
        $this->assertSame('Hello.', $cues[0]->text);
    }

    public function test_rejects_files_that_are_not_webvtt(): void
    {
        $this->expectException(VttParseException::class);
        $this->parser->parse("1\n00:00:01,000 --> 00:00:02,000\nThis is an SRT file\n");
    }

    public function test_rejects_webvtt_with_no_cues(): void
    {
        $this->expectException(VttParseException::class);
        $this->parser->parse("WEBVTT\n\nNOTE nothing here\n");
    }

    public function test_word_count_ignores_punctuation_and_keeps_contractions(): void
    {
        $this->assertSame(6, Cue::countWords("Don't worry — it's a well-known trick!"));
        $this->assertSame(0, Cue::countWords(' ... — '));
    }

    public function test_parses_the_bundled_sample_transcript(): void
    {
        $cues = $this->parser->parse(file_get_contents(__DIR__.'/../../public/sample-class.vtt'));
        $speakers = array_unique(array_map(fn (Cue $c) => $c->speaker, $cues));

        $this->assertCount(49, $cues);
        $this->assertEqualsCanonicalizing(
            ['Dana Reyes', 'Marcus Lee', 'Priya Patel', "Jordan's iPhone", 'Room 214 Zoom Room', 'Grace Kim', 'Unknown caller'],
            array_values($speakers),
        );
    }
}
